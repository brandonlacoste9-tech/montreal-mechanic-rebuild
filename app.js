let lang = localStorage.getItem("mm-lang") || "en";

function applyLang(l) {
  lang = l;
  localStorage.setItem("mm-lang", l);
  document.documentElement.lang = l;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const val = I18N[l][el.getAttribute("data-i18n")];
    if (val !== undefined) el.innerHTML = val;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const val = I18N[l][el.getAttribute("data-i18n-ph")];
    if (val !== undefined) el.placeholder = val;
  });
  document.getElementById("langToggle").textContent = l === "en" ? "FR" : "EN";
  document.title = l === "en"
    ? "AAA Mobile Mechanic — Montréal | We Come to You · 5.0★ Rated"
    : "AAA Mécanicien Mobile — Montréal | On vient à vous · 5,0★";
}

document.getElementById("langToggle").addEventListener("click", () => {
  applyLang(lang === "en" ? "fr" : "en");
});

document.getElementById("quoteForm").addEventListener("submit", e => {
  e.preventDefault();
  document.getElementById("formDone").hidden = false;
  e.target.querySelector("button[type=submit]").style.display = "none";
});

